#!/usr/bin/env node
// scripts/gen-env-example.js
//
// Regenerate .env.example from the canonical table in agent-backend/env-config.js.
// The previous .env.example documented three competing LLM naming schemes and
// was the main source of "why is my endpoint ignored?" — generating it means it
// can only describe variables that actually exist.
//
//   node scripts/gen-env-example.js            # write .env.example
//   node scripts/gen-env-example.js --check    # exit 1 if it is out of date

const fs = require("fs");
const path = require("path");
const env = require("../agent-backend/env-config");

const OUT = path.join(__dirname, "..", ".env.example");

// Ordered, with a heading per group. Groups not listed here are appended.
const GROUPS = [
  ["core", "Core"],
  ["llm", "LLM (any OpenAI-compatible endpoint: OpenAI, Groq, OpenRouter, Together, Ollama, vLLM, a proxy, …)"],
  ["auth", "Access control (RBAC + multi-tenancy)"],
  ["sso", "Enterprise SSO (OIDC — OPTIONAL; toggle on from Admin › SSO once set)"],
  ["db", "Database"],
  ["harness", "Harness binaries (auto-discovered on PATH; override if needed)"],
  ["sandbox", "Execution sandbox (containment for agent shell/tools)"],
  ["run", "Run API (headless task submission → result contract)"],
  ["secrets", "Secrets / tokens encryption-at-rest"],
  ["services", "Optional services"],
  ["gateway", "Internal LLM gateway (set by the app; override only if you know why)"],
];

// Variables written UNCOMMENTED with an empty value, because a fresh install is
// expected to fill them in. Everything else is commented out with its default.
const PROMPT_FOR = new Set(["LLM_BASE_URL", "LLM_API_KEY", "LLM_FAST_MODEL", "LLM_REASONING_MODEL", "PORT", "DASHBOARD_ORIGIN"]);

function wrap(text, width, prefix) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = "";
  for (const w of words) {
    if (line && (line + " " + w).length > width) { lines.push(line); line = w; }
    else line = line ? line + " " + w : w;
  }
  if (line) lines.push(line);
  return lines.map((l) => prefix + l).join("\n");
}

function render() {
  const all = env.describe();
  const seen = new Set();
  const out = [];

  out.push("# ── Environment ──────────────────────────────────────────────────────");
  out.push("# GENERATED by scripts/gen-env-example.js from agent-backend/env-config.js.");
  out.push("# Edit the table there, not this file.");
  out.push("#");
  out.push("# Copy to `.env` and fill in. Everything is optional EXCEPT an LLM endpoint");
  out.push("# (set it here or in the app's Settings; Settings wins).");
  out.push("#");
  out.push("# Variable names carry NO product name, deliberately — a rebrand never touches");
  out.push("# your .env, CI config or secret manager. See docs/rebranding.md.");
  out.push("#");
  out.push("# IMPORTANT for Docker: compose's `env_file` does NOT strip inline \"# ...\"");
  out.push("# comments the way dotenv does — keep comments on their OWN lines, or a value");
  out.push("# like DASHBOARD_ORIGIN will silently include the comment text.");
  out.push("");

  const groupNames = [...GROUPS.map(([g]) => g), ...new Set(all.map((v) => v.group))];
  for (const group of groupNames) {
    const vars = all.filter((v) => v.group === group && !seen.has(v.name));
    if (!vars.length) continue;
    vars.forEach((v) => seen.add(v.name));

    const title = (GROUPS.find(([g]) => g === group) || [group, group])[1];
    out.push(`# ── ${title} ──`);
    for (const v of vars) {
      out.push(wrap(v.desc, 76, "# "));
      const shown = PROMPT_FOR.has(v.name)
        ? `${v.name}=${v.default === "" || v.default === undefined ? "" : v.default}`
        : `# ${v.name}=${v.default === "" || v.default === false || v.default === undefined ? "" : v.default}`;
      out.push(shown);
      out.push("");
    }
  }

  out.push("# ── Migrating from an older release ──");
  out.push("# Variable names changed to brand-free, functional prefixes. The app FAILS AT");
  out.push("# BOOT on a legacy name rather than silently defaulting — an unset");
  out.push("# AUTH_SUPERADMIN_KEY means auth-bypass dev mode, so a silent fallback would");
  out.push("# boot a deployment wide open. To rewrite an existing file in place:");
  out.push("#   node scripts/migrate-env.js .env --dry-run");
  out.push("#   node scripts/migrate-env.js .env");
  out.push("");

  return out.join("\n");
}

const content = render();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf-8") : "";
  if (current !== content) {
    console.error("[env] .env.example is out of date. Run: node scripts/gen-env-example.js");
    process.exit(1);
  }
  console.log("[env] .env.example is up to date.");
} else {
  fs.writeFileSync(OUT, content, "utf-8");
  console.log(`[env] wrote ${OUT}`);
}
